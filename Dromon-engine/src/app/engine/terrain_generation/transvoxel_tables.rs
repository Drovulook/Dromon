//! Tables du **Transvoxel** (Eric Lengyel, <http://transvoxel.org/>) : les
//! **cellules de transition** qui cousent les déchirures entre deux niveaux de LOD.
//!
//! ## Le problème que ça résout
//! Deux chunks voisins à des LOD différents échantillonnent le champ à des pas
//! distincts (`step = 1 << lod`). Sur leur face commune, le bord fin porte plus de
//! sommets que le bord grossier : les surfaces ne coïncident pas → fentes. La
//! cellule de transition est une fine couche insérée du côté **haute résolution**
//! qui raccorde ses 9 échantillons de face aux 4 du côté basse résolution.
//!
//! ## Numérotation des 13 points (PROPRE au Transvoxel, ≠ cube de Bourke)
//! Une cellule de transition n'est pas un cube Marching Cubes : elle a sa **propre**
//! numérotation de 13 points. Elle n'utilise donc jamais les 8 coins de
//! [`super::marching_cubes`] — les deux jeux de tables cohabitent sans conflit.
//!
//! ```text
//!   Face haute réso (9 pts, w=0)        Face basse réso (4 pts, w>0)
//!     6----7----8                          B---------C
//!     |    |    |                          |         |
//!     3----4----5                          |         |
//!     |    |    |                          |         |
//!     0----1----2                          9---------A
//!   (u → droite, v → haut)     9,A,B,C sous 0,2,6,8 respectivement
//! ```
//!
//! Indices 0..8 = grille 3×3 rangée par lignes (`u = i%3`, `v = i/3`). Indices
//! 9,A,B,C (10,11,12) = 4 coins de la face grossière, alignés en (u,v) sur 0,2,6,8
//! mais décalés en profondeur (w) — cf. [`TRANSITION_CORNER_UV`].
//!
//! ## ⚠️ Convention de signe INVERSÉE vs Bourke — LE piège
//! Le code de cas (9 bits) adresse [`TRANSITION_CELL_CLASS`]. Chez Lengyel, le bit
//! est posé quand le coin est **plein** (`d > ISO_LEVEL`) — l'**inverse** de
//! `marching_cubes.rs`, où le bit est posé quand le coin est *vide* (`d < ISO_LEVEL`).
//! Le code de cas de transition DOIT être calculé avec la convention « plein »,
//! sinon on adresse la mauvaise classe. Les cubes réguliers, eux, gardent la
//! convention de Bourke : rien à changer côté MC.
//!
//! Poids des bits (spirale : anneau extérieur puis centre) :
//! ```text
//!   bit   0x001 0x002 0x004 0x008 0x010 0x020 0x040 0x080 0x100
//!   point   0     1     2     5     8     7     6     3     4
//! ```
//!
//! ## Enchaînement des tables
//! 1. `class = TRANSITION_CELL_CLASS[case] & 0x7F` (le bit 0x80 = enroulement à
//!    inverser ; ignoré ici car le mailleur ré-oriente déjà via le gradient).
//! 2. `data = TRANSITION_CELL_DATA[class]` → `vertex_count`, `triangle_count`,
//!    `vertex_index` (triangles = triplets d'indices dans la liste de sommets locale).
//! 3. Position du sommet local `k` : [`transition_edge(case, k)`] donne les 2 coins
//!    (parmi les 13) de l'arête où il se pose ; on interpole comme en MC.
//!
//! ## Ce qu'on ignore volontairement
//! - **L'octet haut** de [`TRANSITION_VERTEX_DATA`] (réutilisation de sommets entre
//!   cellules) : le mailleur déduplique déjà via sa `FxHashMap`.
//! - **Le bit 0x80** de [`TRANSITION_CELL_CLASS`] et [`TRANSITION_CORNER_DATA`]
//!   (données de réutilisation) : l'enroulement est recalculé par le gradient.
//!
//! Données transcrites verbatim depuis le portage `TheGreatB3/transvoxel-data-rs`
//! (lui-même dérivé du code de référence d'Eric Lengyel).

// Tables pas encore consommées par le mailleur (intégration = étape suivante).
#![allow(dead_code)]

/// Triangulation d'une classe d'équivalence (une des 56) de cellule de transition.
#[derive(Copy, Clone)]
pub struct TransitionCellData {
    /// Quartet haut = nombre de sommets ; quartet bas = nombre de triangles.
    geometry_counts: u8,
    /// Triangles par triplets d'indices (dans la liste de sommets locale de la
    /// cellule). `!0` (=255) = remplissage.
    pub vertex_index: [u8; 36],
}

impl TransitionCellData {
    /// Nombre de sommets distincts produits par cette classe.
    #[inline]
    pub fn vertex_count(&self) -> u8 {
        self.geometry_counts >> 4
    }

    /// Nombre de triangles produits par cette classe.
    #[inline]
    pub fn triangle_count(&self) -> u8 {
        self.geometry_counts & 0x0F
    }
}

/// Coordonnées locales `[u, v, side]` des 13 points (cf. schéma en tête de module) :
/// `u, v ∈ {0,1,2}` (demi-cellules dans le plan de la face) ; `side` = 0 pour la face
/// haute réso (w=0), 1 pour la face basse réso. Le mailleur convertit `(u,v,side)` en
/// position monde (choix de l'épaisseur w et de l'orientation de la face = étape
/// suivante, hors de cette table).
pub const TRANSITION_CORNER_UV: [[u8; 3]; 13] = [
    [0, 0, 0], // 0
    [1, 0, 0], // 1
    [2, 0, 0], // 2
    [0, 1, 0], // 3
    [1, 1, 0], // 4
    [2, 1, 0], // 5
    [0, 2, 0], // 6
    [1, 2, 0], // 7
    [2, 2, 0], // 8
    [0, 0, 1], // 9  (sous 0)
    [2, 0, 1], // A=10 (sous 2)
    [0, 2, 1], // B=11 (sous 6)
    [2, 2, 1], // C=12 (sous 8)
];

/// Les 2 coins (parmi les 13) de l'arête portant le sommet local `vertex` du cas
/// `case`. On ne lit que l'**octet bas** de [`TRANSITION_VERTEX_DATA`] : ses 2 quartets
/// sont les indices des extrémités de l'arête (l'octet haut, réutilisation, est ignoré).
#[inline]
pub fn transition_edge(case: usize, vertex: usize) -> (u8, u8) {
    let code = TRANSITION_VERTEX_DATA[case][vertex] & 0x00FF;
    ((code >> 4) as u8, (code & 0x0F) as u8)
}

