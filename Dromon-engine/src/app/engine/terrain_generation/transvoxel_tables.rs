#[cfg(test)]
mod tests {
    use super::*;

    /// Toute classe (bit 0x80 retiré) doit indexer une entrée valide de DATA.
    #[test]
    fn classes_in_range() {
        for &c in TRANSITION_CELL_CLASS.iter() {
            assert!((c & 0x7F) < TRANSITION_CELL_DATA.len() as u8);
        }
    }

    /// Cohérence de chaque classe : les index de triangle référencent des sommets
    /// existants, et les comptes annoncés collent aux données non-remplissage.
    #[test]
    fn cell_data_consistent() {
        for data in TRANSITION_CELL_DATA.iter() {
            let nv = data.vertex_count();
            let nt = data.triangle_count() as usize;
            for &idx in data.vertex_index[..nt * 3].iter() {
                assert!(idx < nv, "index de sommet {} >= count {}", idx, nv);
            }
            // Au-delà des `nt` triangles, tout est remplissage (!0).
            for &idx in data.vertex_index[nt * 3..].iter() {
                assert_eq!(idx, !0);
            }
        }
    }

    /// Les arêtes décodées ne référencent que des points valides (0..12), pour le
    /// nombre de sommets annoncé par la classe du cas.
    #[test]
    fn edges_reference_valid_corners() {
        for case in 0..512 {
            let class = (TRANSITION_CELL_CLASS[case] & 0x7F) as usize;
            let nv = TRANSITION_CELL_DATA[class].vertex_count() as usize;
            for k in 0..nv {
                let (a, b) = transition_edge(case, k);
                assert!(a < 13 && b < 13, "cas {} sommet {}: coins {},{}", case, k, a, b);
            }
        }
    }
}
